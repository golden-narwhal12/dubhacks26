import type { Evidence, Part, Terminal } from '../domain/schema';

// These are electrical packages, not execution models or physical inventory claims.
const assets = { renderer: 'generic', geometry: 'illustrative' } as const;
const pin = (
  id: string,
  label: string,
  kind: Terminal['kind'] = 'passive',
  requirements?: string,
  physicalPin?: number,
  capabilities: string[] = [],
): Terminal => ({
  id,
  label,
  kind,
  capabilities,
  evidenceIds: [],
  ...(requirements ? { requirements } : {}),
  ...(physicalPin !== undefined ? { physicalPin } : {}),
});
const ground = (id = 'gnd', physicalPin?: number): Terminal => ({
  ...pin(id, 'GND', 'ground', undefined, physicalPin),
  voltage: 0,
});
const source = (
  title: string,
  url: string,
  revision: string,
  location: string,
  fact: string,
): Evidence => ({ id: 'datasheet', title, url, revision, location, fact, status: 'verified' });
const generic = (
  id: string,
  name: string,
  kind: Part['kind'],
  category: Part['category'],
  terminals: Terminal[],
  description: string,
  assumptions: string,
): Part => ({
  id,
  version: 1,
  name,
  manufacturer: 'Generic',
  mpn: 'Unspecified',
  revision: 'Trace logical template 1',
  kind,
  category,
  description,
  coverage: assumptions,
  terminals: terminals.map((t) => ({ ...t, evidenceIds: ['assumptions'] })),
  internalGroups: [],
  evidence: [
    {
      id: 'assumptions',
      title: 'Trace editable design assumptions',
      url: 'https://docs.arduino.cc/learn/electronics/',
      revision: 'Trace logical template 1',
      location: 'Logical roles only; physical package and ratings unconfirmed',
      fact: assumptions,
      status: 'provisional',
    },
  ],
  verifiedMapping: false,
  constraints: false,
  simulation: 'none',
  assets,
});
const exact = (
  id: string,
  name: string,
  manufacturer: string,
  mpn: string,
  kind: Part['kind'],
  category: Part['category'],
  terminals: Terminal[],
  evidence: Evidence,
  description: string,
  coverage: string,
): Part => ({
  id,
  version: 1,
  name,
  manufacturer,
  mpn,
  revision: evidence.revision,
  kind,
  category,
  description,
  coverage,
  terminals: terminals.map((t) => ({ ...t, evidenceIds: [evidence.id] })),
  internalGroups: [],
  evidence: [evidence],
  verifiedMapping: true,
  // Documented facts are inspectable; this does not claim comprehensive electrical-rule coverage.
  constraints: true,
  simulation: 'none',
  assets,
});

