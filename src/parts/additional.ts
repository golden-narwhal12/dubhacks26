for (const terminal of shifter.terminals) {
  const lowSide = terminal.id === 'lv' || /^lv[1-4]$/.test(terminal.id) || terminal.id === 'gnd';
  terminal.header = lowSide ? 'JP3' : 'JP4';
  terminal.physicalPin =
    terminal.id === 'lv' || terminal.id === 'hv'
      ? 6
      : terminal.kind === 'ground'
        ? 1
        : 6 - Number(terminal.id.slice(2));
}
